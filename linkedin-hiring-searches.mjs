#!/usr/bin/env node
/**
 * linkedin-hiring-searches.mjs — Generate tuned LinkedIn content-search URLs
 * for "we're hiring" posts. Zero-token, zero-auth, no scraping.
 *
 * Why URLs and not an API: LinkedIn's official Developer API exposes no
 * post/content search (Posts API only creates posts and reads ones you own),
 * so there is nothing sanctioned to call. These URLs drive LinkedIn's OWN
 * search UI, which is just you browsing: no ToS exposure, no account risk.
 * You skim the results and feed the good ones to outreach-post-lead.mjs.
 *
 * Hiring posts are the warmest outreach leads available: the poster is a named
 * human explicitly inviting contact, unlike a cold recruiter.
 *
 * Writes a clickable list to data/linkedin-hiring-searches.md and prints it.
 *
 * Usage:
 *   node linkedin-hiring-searches.mjs                  # all archetypes, past week
 *   node linkedin-hiring-searches.mjs --since past-24h # past-24h|past-week|past-month
 *   node linkedin-hiring-searches.mjs --role ai-ml     # one archetype
 *   node linkedin-hiring-searches.mjs --dry-run        # print only, no file
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { resolvePaths } from './lib/paths.mjs';

const P = resolvePaths(import.meta.url);
const OUT_PATH = join(P.dataDir, 'linkedin-hiring-searches.md');

const args = process.argv.slice(2);
const dryRun = args.includes('--dry-run');
const sinceIdx = args.indexOf('--since');
const roleIdx = args.indexOf('--role');
const VALID_SINCE = new Set(['past-24h', 'past-week', 'past-month']);
const since = sinceIdx !== -1 && VALID_SINCE.has(args[sinceIdx + 1]) ? args[sinceIdx + 1] : 'past-week';
const roleFilter = roleIdx !== -1 ? args[roleIdx + 1] : null;

// Curated queries, keyed by the same archetypes outreach-draft.mjs uses.
// Kept tuned rather than a cartesian blowup: broad queries drown in LinkedIn's
// job-board SEO pages, and quoted phrases are what actually match real posts.
const SEARCHES = {
  'backend': [
    ['SWE new grad', '"we\'re hiring" "software engineer" "new grad"'],
    ['SWE team-is-hiring', '"my team is hiring" "software engineer" "entry level"'],
  ],
  'ai-ml': [
    ['ML/AI new grad', '"we\'re hiring" "machine learning engineer" OR "AI engineer" "new grad"'],
    ['AI early career', '"now hiring" "AI engineer" "early career" OR "entry level"'],
  ],
  'data': [
    ['Data new grad', '"we\'re hiring" "data engineer" OR "data scientist" "new grad" OR "entry level"'],
  ],
  'fde': [
    ['Forward deployed', '"we\'re hiring" "forward deployed engineer" OR "solutions engineer"'],
  ],
  'sponsorship': [
    ['Sponsorship-friendly', 'hiring "new grad" "visa sponsorship" software engineer'],
    ['CPT/OPT-friendly', 'hiring "new grad" "will sponsor" OR "sponsorship available" engineer'],
  ],
  'general': [
    ['2026 grads', '"hiring" "2026 grad" OR "class of 2026" software engineer'],
    ['Direct-DM posts', '"we\'re hiring" "DM me" engineer "new grad"'],
  ],
};

function contentSearchUrl(keywords) {
  const q = new URLSearchParams({ keywords });
  // datePosted/sortBy are quoted values in LinkedIn's content-search UI.
  return `https://www.linkedin.com/search/results/content/?${q}`
    + `&datePosted=%22${since}%22&sortBy=%22date_posted%22`;
}

function main() {
  const groups = Object.entries(SEARCHES).filter(([k]) => !roleFilter || k === roleFilter);
  if (groups.length === 0) {
    console.error(`Unknown --role "${roleFilter}". Valid: ${Object.keys(SEARCHES).join(', ')}`);
    process.exit(1);
  }

  const lines = [
    '# LinkedIn hiring-post searches',
    '',
    `Generated by \`linkedin-hiring-searches.mjs\` (window: ${since}, sorted newest first).`,
    'Click through, skim for real posts (not job-board pages), then capture a good one:',
    '',
    '```bash',
    'node outreach-post-lead.mjs --company "Acme" --role "Software Engineer, New Grad" \\',
    '  --name "Jane Doe" --profile https://www.linkedin.com/in/janedoe/ \\',
    '  --post https://www.linkedin.com/posts/janedoe_...',
    '```',
    '',
  ];

  for (const [archetype, queries] of groups) {
    lines.push(`## ${archetype}`, '');
    for (const [label, keywords] of queries) {
      const url = contentSearchUrl(keywords);
      lines.push(`- [${label}](${url})`, `  - \`${keywords}\``);
    }
    lines.push('');
  }

  const md = lines.join('\n');
  for (const [archetype, queries] of groups) {
    console.log(`\n${archetype}`);
    for (const [label, keywords] of queries) {
      console.log(`  ${label}: ${contentSearchUrl(keywords)}`);
    }
  }
  if (dryRun) {
    console.log('\n(dry run — file not written)');
    return;
  }
  writeFileSync(OUT_PATH, md, 'utf-8');
  console.log(`\nWrote ${OUT_PATH}`);
}

main();
